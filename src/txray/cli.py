"""Command-line interface.

Exit codes: 0 success, 1 invalid input/configuration, 2 usage error (argparse),
3 when ``--fail-on`` is set and a finding reaches that severity.
"""

from __future__ import annotations

import argparse
import json
import secrets
import sys
from pathlib import Path
from typing import Any, TextIO

from txray import __version__
from txray.analysis.transaction import TxRequest
from txray.config import Settings, hash_api_key, load_settings
from txray.errors import TxrayError
from txray.evm.cfg import ControlFlowGraph
from txray.evm.disassembler import disassemble
from txray.evm.metadata import parse_metadata
from txray.hexutil import int_from_hex_or_dec, normalize_address, parse_hex
from txray.logs import configure_logging
from txray.models import Severity
from txray.rules import RULES
from txray.service import Txray

EXIT_FINDINGS = 3
_COLORS = {
    "info": "\033[2m",
    "low": "\033[36m",
    "medium": "\033[33m",
    "high": "\033[31m",
    "critical": "\033[1;41;97m",
}
_VERDICT = {"pass": "\033[32m", "warn": "\033[33m", "block": "\033[1;31m"}
_RESET = "\033[0m"


def _read_source(value: str) -> str:
    if value == "-":
        return sys.stdin.read()
    return Path(value).read_text(encoding="utf-8")


def _paint(text: str, style: str | None, enabled: bool) -> str:
    return f"{style}{text}{_RESET}" if enabled and style else text


def render(report: dict[str, Any], out: TextIO, color: bool) -> None:
    verdict = report["verdict"]
    out.write(
        _paint(f"{verdict.upper()}", _VERDICT.get(verdict), color)
        + f"  score {report['score']}/100  ({report['kind']}, report {report['id']})\n"
    )
    decoded = report.get("decoded", {})
    call = decoded.get("call")
    if call:
        out.write(
            f"\n  call    {call.get('function') or call.get('selector') or '(no calldata)'}"
            f" on {call['target']}\n"
        )
        if not call.get("inner"):
            for name, value in call.get("args", {}).items():
                out.write(f"          {name} = {value}\n")
        for inner in call.get("inner", []):
            label = inner.get("function") or inner.get("selector")
            out.write(f"          -> {label} on {inner['target']}\n")
    if "digest" in decoded:
        out.write(f"\n  type    {decoded['primary_type']} ({decoded['classification']})\n")
        out.write(f"  digest  {decoded['digest']}\n")
    if "siwe" in decoded:
        out.write(
            f"\n  SIWE    domain={decoded['siwe']['domain']} address={decoded['siwe']['address']}\n"
        )
    profile = decoded.get("profile")
    if profile:
        out.write(f"\n  code    {profile['size']} bytes, {profile['code_hash']}\n")
        if profile.get("compiler"):
            out.write(f"  built   {profile['compiler']}\n")
        count, complete = len(profile["functions"]), profile["cfg_complete"]
        out.write(f"  funcs   {count} selectors, CFG complete: {complete}\n")
        for fn in profile["functions"]:
            reaches = ",".join(
                r for r in fn["reaches"] if r in ("SELFDESTRUCT", "DELEGATECALL", "CREATE2")
            )
            name = fn["names"][0] if fn["names"] else ""
            out.write(f"          {fn['selector']} {name:<40} {reaches}".rstrip() + "\n")

    findings = report["findings"]
    out.write("\n" if findings else "\n  no findings\n")
    for f in findings:
        tag = _paint(f"[{f['severity'].upper():>8}]", _COLORS.get(f["severity"]), color)
        out.write(f"  {tag} {f['rule_id']} {f['title']}\n             {f['detail']}\n")
    for note in report.get("notes", []):
        out.write(f"  note: {note}\n")


def rules_table() -> str:
    return "".join(f"{r.id:<7} {r.severity.label:<9} {r.title}\n" for r in RULES.values())


def rules_markdown() -> str:
    """Rule catalog as Markdown; docs/RULES.md is generated from this."""
    groups = {
        "INT": "Address intelligence",
        "TX": "Transactions",
        "SIG": "EIP-712 typed data",
        "MSG": "personal_sign / eth_sign",
        "BC": "Bytecode",
    }
    lines = [
        "# Detection rules",
        "",
        "Generated by `txray rules --markdown`; do not edit by hand.",
        "Severities are defaults: some rules raise or lower them with context",
        "(known spender, account without code, native value attached).",
    ]
    for prefix, title in groups.items():
        lines += [
            "",
            f"## {title}",
            "",
            "| ID | Default | Title | Rationale |",
            "|---|---|---|---|",
        ]
        for r in RULES.values():
            if r.id.rstrip("0123456789") == prefix:
                lines.append(f"| {r.id} | {r.severity.label} | {r.title} | {r.rationale} |")
    return "\n".join(lines) + "\n"


def _common(p: argparse.ArgumentParser, *, sender: bool = True) -> None:
    p.add_argument("--chain-id", type=int, default=1, help="chain the wallet is on (default 1)")
    p.add_argument("--offline", action="store_true", help="do not query any RPC endpoint")
    if sender:
        p.add_argument("--from", dest="sender", help="account asked to sign")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="txray", description=__doc__.splitlines()[0] if __doc__ else None
    )
    parser.add_argument("--version", action="version", version=f"txray {__version__}")
    parser.add_argument("--config", help="TOML configuration file")
    parser.add_argument("--json", action="store_true", help="print the raw JSON report")
    parser.add_argument("--no-color", action="store_true")
    parser.add_argument(
        "--fail-on",
        choices=[s.label for s in Severity if s > Severity.INFO],
        help="exit with status 3 when a finding reaches this severity",
    )
    parser.add_argument("--log-level", default=None)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("tx", help="analyze a transaction request")
    p.add_argument("--to", help="destination (omit for contract creation)")
    p.add_argument("--data", default="0x", help="calldata hex")
    p.add_argument("--value", default="0", help="wei, decimal or 0x-hex")
    _common(p)

    p = sub.add_parser("typed-data", help="analyze an eth_signTypedData_v4 payload")
    p.add_argument("file", help="JSON file, or - for stdin")
    _common(p)

    p = sub.add_parser("message", help="analyze a personal_sign / eth_sign payload")
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument("--text", help="message as text")
    group.add_argument("--hex", help="message as 0x-hex")
    group.add_argument("--file", help="read the message text from a file")
    p.add_argument("--method", choices=["personal_sign", "eth_sign"], default="personal_sign")
    p.add_argument("--origin", help="site that requested the signature")
    _common(p)

    p = sub.add_parser("bytecode", help="profile contract bytecode")
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument("--code", help="runtime bytecode hex")
    group.add_argument("--file", help="file containing runtime bytecode hex")
    group.add_argument("--address", help="fetch code from the configured RPC")
    _common(p, sender=False)

    p = sub.add_parser("disasm", help="disassemble bytecode")
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument("--code")
    group.add_argument("--file")
    p.add_argument("--blocks", action="store_true", help="group by basic block with reachability")

    p = sub.add_parser("rules", help="list detection rules")
    p.add_argument("--markdown", action="store_true", help="print the catalog as Markdown")
    p = sub.add_parser("report", help="print a stored report")
    p.add_argument("id")

    sub.add_parser("keygen", help="generate an API key and the hash to configure")

    p = sub.add_parser("serve", help="run the HTTP API")
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=8080)
    p.add_argument(
        "--allow-anonymous",
        action="store_true",
        help="serve without API keys (local development only)",
    )
    return parser


def _load_code(args: argparse.Namespace) -> bytes:
    text = args.code if args.code is not None else Path(args.file).read_text(encoding="utf-8")
    return parse_hex(text.strip(), field="code")


def _emit(report: dict[str, Any], args: argparse.Namespace, out: TextIO) -> int:
    if args.json:
        out.write(json.dumps(report, indent=2) + "\n")
    else:
        render(report, out, color=not args.no_color and out.isatty())
    if (
        args.fail_on
        and Severity.parse(report["max_severity"]) >= Severity.parse(args.fail_on)
        and report["findings"]
    ):
        return EXIT_FINDINGS
    return 0


def run(args: argparse.Namespace, settings: Settings, out: TextIO) -> int:
    cmd = args.command
    if cmd == "rules":
        out.write(rules_markdown() if args.markdown else rules_table())
        return 0
    if cmd == "keygen":
        key = secrets.token_urlsafe(32)
        out.write(
            f"api key : {key}\nsha256  : {hash_api_key(key)}\n"
            "Configure the sha256 value in TXRAY_API_KEY_HASHES; give the key to clients.\n"
        )
        return 0
    if cmd == "disasm":
        code = _load_code(args)
        meta = parse_metadata(code)
        body = code[: len(code) - meta.raw_length] if meta else code
        instructions = disassemble(body)
        if not args.blocks:
            out.writelines(f"{ins}\n" for ins in instructions)
        else:
            cfg = ControlFlowGraph(instructions)
            reach = cfg.explore(0)
            for start, block in sorted(cfg.blocks.items()):
                mark = "" if start in reach.reachable else "  (unreachable)"
                succ = ",".join(f"{t:#x}" for t in sorted(reach.edges.get(start, ())))
                out.write(f"block {start:#x}{mark} -> [{succ}]\n")
                out.writelines(f"    {ins}\n" for ins in block.instructions)
        if meta:
            out.write(
                f"; metadata: {meta.compiler or 'unknown compiler'} {meta.source_hash or ''}\n"
            )
        return 0
    if cmd == "serve":
        import uvicorn

        from txray.api import create_app

        if args.allow_anonymous:
            settings.allow_anonymous = True
        app = create_app(settings)
        uvicorn.run(app, host=args.host, port=args.port, log_config=None, access_log=False)
        return 0

    service = Txray(settings)
    try:
        if cmd == "report":
            if service.store is None:
                raise TxrayError("no database configured (set TXRAY_DB or db_path)")
            stored = service.store.get_report(args.id)
            if stored is None:
                raise TxrayError(f"report {args.id} not found")
            return _emit(stored, args, out)
        ctx = service.context(
            args.chain_id,
            getattr(args, "sender", None),
            getattr(args, "origin", None),
            offline=args.offline,
        )
        if cmd == "tx":
            tx = TxRequest(
                to=normalize_address(args.to, field="--to") if args.to else None,
                data=parse_hex(args.data, field="--data"),
                value=int_from_hex_or_dec(args.value, field="--value"),
                sender=ctx.sender,
            )
            return _emit(service.transaction(tx, ctx), args, out)
        if cmd == "typed-data":
            return _emit(service.typed_data(_read_source(args.file), ctx), args, out)
        if cmd == "message":
            if args.hex is not None:
                payload = args.hex
            else:
                payload = args.text if args.text is not None else _read_source(args.file)
            return _emit(service.message(args.method, payload, ctx), args, out)
        if cmd == "bytecode":
            if args.address:
                return _emit(service.bytecode(address=args.address, ctx=ctx), args, out)
            return _emit(service.bytecode(code=_load_code(args), ctx=ctx), args, out)
    finally:
        service.close()
    raise AssertionError(f"unhandled command {cmd}")


def main(argv: list[str] | None = None, out: TextIO | None = None) -> int:
    out = out or sys.stdout
    args = build_parser().parse_args(argv)
    try:
        settings = load_settings(args.config)
        # Analysis commands log at WARNING unless asked: stdout is the report.
        default_level = settings.log_level if args.command == "serve" else "WARNING"
        configure_logging(args.log_level or default_level, settings.log_json)
        return run(args, settings, out)
    except (TxrayError, OSError) as exc:
        sys.stderr.write(f"txray: error: {exc}\n")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
